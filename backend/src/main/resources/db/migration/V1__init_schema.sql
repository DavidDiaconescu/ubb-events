-- Initial schema for UBB Events (R7 - persistence)

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    first_name    VARCHAR(255) NOT NULL,
    last_name     VARCHAR(255) NOT NULL,
    faculty       VARCHAR(255) NOT NULL,
    study_year    INTEGER      NOT NULL,
    global_role   VARCHAR(32)  NOT NULL,
    enabled       BOOLEAN      NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email) -- BR-28
);

CREATE TABLE organizations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    description   TEXT         NOT NULL,
    logo_url      VARCHAR(255),
    contact_email VARCHAR(255) NOT NULL,
    status        VARCHAR(32)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_organizations_name UNIQUE (name)
);

CREATE TABLE memberships (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL,
    organization_id BIGINT      NOT NULL,
    role            VARCHAR(32) NOT NULL,
    joined_at       TIMESTAMPTZ NOT NULL,
    active          BOOLEAN     NOT NULL,
    CONSTRAINT fk_memberships_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_memberships_organization_id FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT uq_memberships_user_org UNIQUE (user_id, organization_id)
);

CREATE TABLE venues (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    address      VARCHAR(255),
    max_capacity INTEGER,
    online       BOOLEAN      NOT NULL
);

CREATE TABLE events (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id        BIGINT       NOT NULL,
    venue_id               BIGINT,
    created_by_id          BIGINT       NOT NULL,
    title                  VARCHAR(255) NOT NULL,
    description            TEXT         NOT NULL,
    category               VARCHAR(32)  NOT NULL,
    start_time             TIMESTAMPTZ  NOT NULL,
    end_time               TIMESTAMPTZ  NOT NULL,
    capacity               INTEGER      NOT NULL,
    registration_opens_at  TIMESTAMPTZ  NOT NULL,
    registration_closes_at TIMESTAMPTZ  NOT NULL,
    visibility             VARCHAR(32)  NOT NULL,
    status                 VARCHAR(32)  NOT NULL,
    cancellation_reason    VARCHAR(255),
    version                BIGINT       NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_events_organization_id FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_events_venue_id FOREIGN KEY (venue_id) REFERENCES venues (id),
    CONSTRAINT fk_events_created_by_id FOREIGN KEY (created_by_id) REFERENCES users (id),
    -- BR-02 .. BR-04
    CONSTRAINT ck_events_time_range CHECK (end_time > start_time),
    CONSTRAINT ck_events_capacity_positive CHECK (capacity > 0),
    CONSTRAINT ck_events_registration_before_start CHECK (registration_closes_at <= start_time),
    CONSTRAINT ck_events_registration_window CHECK (registration_opens_at < registration_closes_at)
);

CREATE INDEX ix_events_organization_id ON events (organization_id);
CREATE INDEX ix_events_status ON events (status);

CREATE TABLE event_organizers (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT      NOT NULL,
    user_id  BIGINT      NOT NULL,
    role     VARCHAR(32) NOT NULL,
    CONSTRAINT fk_event_organizers_event_id FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_event_organizers_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_event_organizers_event_user UNIQUE (event_id, user_id)
);

CREATE TABLE registrations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          BIGINT       NOT NULL,
    user_id           BIGINT       NOT NULL,
    status            VARCHAR(32)  NOT NULL,
    waitlist_position INTEGER,
    check_in_code     VARCHAR(255) NOT NULL,
    registered_at     TIMESTAMPTZ  NOT NULL,
    checked_in_at     TIMESTAMPTZ,
    late_cancellation BOOLEAN      NOT NULL,
    CONSTRAINT fk_registrations_event_id FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_registrations_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_registrations_check_in_code UNIQUE (check_in_code) -- BR-21
);

-- BR-12: at most one active registration per user and event
CREATE UNIQUE INDEX ux_registrations_event_user_active
    ON registrations (event_id, user_id)
    WHERE status IN ('CONFIRMED', 'WAITLISTED');

CREATE INDEX ix_registrations_event_id ON registrations (event_id);
CREATE INDEX ix_registrations_user_id ON registrations (user_id);

CREATE TABLE tasks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT       NOT NULL,
    assignee_id BIGINT       NOT NULL,
    title       VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    due_date    DATE,
    status      VARCHAR(32)  NOT NULL,
    CONSTRAINT fk_tasks_event_id FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_tasks_assignee_id FOREIGN KEY (assignee_id) REFERENCES users (id)
);

CREATE TABLE announcements (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  BIGINT       NOT NULL,
    author_id BIGINT       NOT NULL,
    title     VARCHAR(255) NOT NULL,
    content   TEXT         NOT NULL,
    audience  VARCHAR(32)  NOT NULL,
    sent_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_announcements_event_id FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_announcements_author_id FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT       NOT NULL,
    event_id     BIGINT,
    type         VARCHAR(32)  NOT NULL,
    channel      VARCHAR(32)  NOT NULL,
    message      VARCHAR(255) NOT NULL,
    read         BOOLEAN      NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_notifications_recipient_id FOREIGN KEY (recipient_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_event_id FOREIGN KEY (event_id) REFERENCES events (id)
);

CREATE TABLE feedback (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT       NOT NULL,
    user_id      BIGINT       NOT NULL,
    rating       INTEGER      NOT NULL,
    comment      VARCHAR(255),
    anonymous    BOOLEAN      NOT NULL,
    submitted_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_feedback_event_id FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_feedback_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    -- BR-24
    CONSTRAINT uq_feedback_event_user UNIQUE (event_id, user_id),
    CONSTRAINT ck_feedback_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT       NOT NULL,
    action      VARCHAR(255) NOT NULL,
    entity_type VARCHAR(255) NOT NULL,
    entity_id   BIGINT       NOT NULL, -- intentionally no FK (polymorphic reference)
    details     TEXT,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_audit_logs_actor_id FOREIGN KEY (actor_id) REFERENCES users (id)
);